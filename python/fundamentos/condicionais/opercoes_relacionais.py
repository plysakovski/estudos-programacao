# criando variáveis de teste
a = 10
b = 3
c = 2

print("1.", a > c)
# 10 > 2 ou seja o resultado é True
print("2.", a != c)
# 10 != 2 ou seja o resultado é True
print("3.", a == c * b)
# 10 == 2 * 3 => 10 == 6 ou seja o resultado é False
print("4.", a >= c * b)
# 10 >= 2 * 3 ou seja o resultado é True
print("5.", (a * b) <= (a // c % b))
# 10 * 3 <= 10 // 2 % 3 => 30 <= 5 ou seja o resultado é False
